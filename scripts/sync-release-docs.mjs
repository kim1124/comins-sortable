import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname } from 'node:path';

const start = '<!-- release-summary:start -->';
const end = '<!-- release-summary:end -->';

function summaryBlock(source, content) {
  const block = `${start}\n${content}\n${end}`;
  const opening = source.indexOf(start);
  const closing = source.indexOf(end);
  if (opening < 0 && closing < 0) {
    if (!/^# [^\n]+\n/.test(source)) throw new Error('Document title is missing');
    return source.replace(/^(# [^\n]+\n)/, (title) => `${title}\n${block}\n`);
  }
  if (opening < 0 || closing < opening || source.indexOf(start, opening + start.length) >= 0
    || source.indexOf(end, closing + end.length) >= 0) throw new Error('Invalid generated markers');
  return source.slice(0, opening) + block + source.slice(closing + end.length);
}

try {
  if (process.argv.length !== 3 || !['--write', '--check'].includes(process.argv[2])) {
    throw new Error('Use --write or --check');
  }
  const { version } = JSON.parse(readFileSync('package.json', 'utf8'));
  if (!/^\d+\.\d+\.\d+(?:-[\da-zA-Z.-]+)?$/.test(version)) throw new Error('Invalid version');
  const changelog = readFileSync('CHANGELOG.md', 'utf8');
  const sections = changelog.split(/^## /m).slice(1);
  const matching = sections.filter((section) => section.split('\n')[0].trim().split(' - ')[0] === version);
  if (matching.length !== 1) throw new Error('Exactly one changelog entry for the manifest version is required');
  const notes = matching[0].slice(matching[0].indexOf('\n') + 1).trim();
  const highlights = (heading) => {
    const lines = notes.split('\n');
    const index = lines.indexOf(`### ${heading}`);
    if (index < 0) throw new Error(`Missing changelog heading: ${heading}`);
    const next = lines.findIndex((line, i) => i > index && /^###? /.test(line));
    const body = lines.slice(index + 1, next < 0 ? undefined : next).join('\n').trim();
    if (!/^- /m.test(body)) throw new Error(`Missing highlights: ${heading}`);
    return body;
  };
  const english = highlights('Highlights');
  const korean = highlights('주요 변경');
  const changesLink = 'https://github.com/kim1124/comins-sortable/blob/main/CHANGELOG.md';
  // Compute and validate every output before modifying any document.
  const outputs = new Map([
    ['README.md', summaryBlock(readFileSync('README.md', 'utf8'), `## ${version} changes\n\n${english}\n\n[Full changelog](${changesLink}) · [Release status](https://github.com/kim1124/comins-sortable/blob/main/docs/verification/${version}-local-validation.md)\n`)],
    ['docs/README.md', summaryBlock(readFileSync('docs/README.md', 'utf8'), `## ${version} changes / 주요 변경\n\n${english}\n\n${korean}\n\n[Release notes](./releases/latest.md) · [검증·배포 상태](./verification/${version}-local-validation.md)\n`)],
    ['docs/releases/latest.md', `<!-- Generated by npm run docs:sync from CHANGELOG.md; do not edit. -->\n# ${version} release notes / 변경 사항\n\n${notes}\n\nPublication and verification are separate: see [release status](../verification/${version}-local-validation.md).\n`],
  ]);
  // Require a reviewed status document rather than inventing verification evidence.
  if (!existsSync(`docs/verification/${version}-local-validation.md`)) throw new Error('Release validation document is required');
  const stale = [...outputs].filter(([path, content]) => !existsSync(path) || readFileSync(path, 'utf8') !== content);
  if (process.argv[2] === '--check') {
    if (stale.length) throw new Error(`Outdated release documents: ${stale.map(([path]) => path).join(', ')}`);
  } else {
    for (const [path, content] of stale) {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
    }
  }
  process.stdout.write(`release-docs: ${version} ${process.argv[2] === '--check' ? 'PASS' : 'synchronized'}\n`);
} catch (error) {
  process.stderr.write(`release-docs: ${error.message}\n`);
  process.exitCode = 1;
}
